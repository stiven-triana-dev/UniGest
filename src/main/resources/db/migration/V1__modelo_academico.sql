-- UniGest · Modelo PostgreSQL · fase 1
-- Restricciones que no caben en un CHECK (cupo, choques, suma de pesos, autorizaciones)
-- quedan como reglas para la capa de servicios, documentadas en REGLAS_NEGOCIO.md.

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE CHECK (codigo IN ('ADMIN','DOCENTE','ESTUDIANTE')),
    nombre VARCHAR(60) NOT NULL
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL CHECK (length(trim(nombres)) > 0),
    apellidos VARCHAR(100) NOT NULL CHECK (length(trim(apellidos)) > 0),
    correo VARCHAR(180) NOT NULL CHECK (position('@' in correo) > 1),
    clave_hash VARCHAR(255) NOT NULL CHECK (length(clave_hash) >= 20),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_usuarios_correo_insensitive ON usuarios (lower(trim(correo)));

CREATE TABLE usuario_roles (
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    rol_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE programas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE estudiantes (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE RESTRICT,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    programa_id BIGINT NOT NULL REFERENCES programas(id) ON DELETE RESTRICT,
    fecha_ingreso DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE docentes (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE RESTRICT,
    codigo VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE asignaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    creditos SMALLINT NOT NULL CHECK (creditos BETWEEN 1 AND 15),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

-- Una asignatura puede formar parte de más de un programa.
CREATE TABLE planes_estudio (
    programa_id BIGINT NOT NULL REFERENCES programas(id) ON DELETE RESTRICT,
    asignatura_id BIGINT NOT NULL REFERENCES asignaturas(id) ON DELETE RESTRICT,
    semestre_sugerido SMALLINT NOT NULL CHECK (semestre_sugerido BETWEEN 1 AND 16),
    obligatoria BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (programa_id, asignatura_id)
);

CREATE TABLE periodos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PLANIFICADO'
        CHECK (estado IN ('PLANIFICADO','INSCRIPCIONES','EN_CURSO','CERRADO')),
    CONSTRAINT ck_periodo_fechas CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE grupos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asignatura_id BIGINT NOT NULL REFERENCES asignaturas(id) ON DELETE RESTRICT,
    docente_id BIGINT NOT NULL REFERENCES docentes(usuario_id) ON DELETE RESTRICT,
    periodo_id BIGINT NOT NULL REFERENCES periodos(id) ON DELETE RESTRICT,
    codigo VARCHAR(15) NOT NULL,
    cupo INTEGER NOT NULL CHECK (cupo BETWEEN 1 AND 1000),
    estado VARCHAR(12) NOT NULL DEFAULT 'BORRADOR'
        CHECK (estado IN ('BORRADOR','ABIERTO','CERRADO')),
    UNIQUE (periodo_id, asignatura_id, codigo)
);

CREATE TABLE matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(usuario_id) ON DELETE RESTRICT,
    grupo_id BIGINT NOT NULL REFERENCES grupos(id) ON DELETE RESTRICT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA','RETIRADA','FINALIZADA')),
    UNIQUE (estudiante_id, grupo_id),
    UNIQUE (id, grupo_id)
);
CREATE INDEX idx_matriculas_grupo_estado ON matriculas (grupo_id, estado);

CREATE TABLE evaluaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id BIGINT NOT NULL REFERENCES grupos(id) ON DELETE RESTRICT,
    titulo VARCHAR(150) NOT NULL,
    ponderacion NUMERIC(5,2) NOT NULL CHECK (ponderacion > 0 AND ponderacion <= 100),
    fecha DATE,
    publicada BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (id, grupo_id)
);
CREATE INDEX idx_evaluaciones_grupo ON evaluaciones (grupo_id);

CREATE TABLE calificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    evaluacion_id BIGINT NOT NULL,
    grupo_id BIGINT NOT NULL,
    nota NUMERIC(4,2) NOT NULL CHECK (nota BETWEEN 0 AND 5),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (matricula_id, evaluacion_id),
    CONSTRAINT fk_calif_matricula_grupo FOREIGN KEY (matricula_id, grupo_id)
        REFERENCES matriculas (id, grupo_id) ON DELETE RESTRICT,
    CONSTRAINT fk_calif_evaluacion_grupo FOREIGN KEY (evaluacion_id, grupo_id)
        REFERENCES evaluaciones (id, grupo_id) ON DELETE RESTRICT
);
CREATE INDEX idx_calificaciones_matricula ON calificaciones(matricula_id);

-- Historial previsto para cambios posteriores; la aplicación deberá escribirlo
-- en la misma transacción que modifique una nota (NO es automático en fase 1).
CREATE TABLE historial_calificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calificacion_id BIGINT NOT NULL REFERENCES calificaciones(id) ON DELETE RESTRICT,
    modificado_por BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    nota_anterior NUMERIC(4,2) NOT NULL CHECK (nota_anterior BETWEEN 0 AND 5),
    nota_nueva NUMERIC(4,2) NOT NULL CHECK (nota_nueva BETWEEN 0 AND 5),
    motivo VARCHAR(255) NOT NULL CHECK (length(trim(motivo)) > 0),
    fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);
